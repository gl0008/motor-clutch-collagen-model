def run_fixed_force_direction(
    cfg: G4V4Config = G4V4Config(),
    *,
    geometry: TractionGeometry = "normal",
    total_force: float | None = None,
    duration: float | None = None,
    sample_interval: float | None = None,
    spec: NetworkSpec | None = None,
    crosslink_probability: float | None = None,
) -> dict:
    """G4 v4-B: fixed-size cell with deterministic contact-band traction."""

    cfg.validate()
    force = cfg.total_pull_force if total_force is None else float(total_force)
    run_time = cfg.fixed_duration if duration is None else float(duration)
    observe = cfg.fixed_sample_interval if sample_interval is None else float(sample_interval)
    probability = cfg.crosslink_probability if crosslink_probability is None else float(crosslink_probability)
    network, spec, report = build_random_network(
        cfg, spec=spec, crosslink_probability=probability
    )
    center = np.zeros(2)
    patches = select_force_geometry(network, center, geometry, cfg)
    if not patches:
        raise RuntimeError("random network has no eligible cell-surface material points")
    direct = [int(patch.fiber) for patch in patches]
    distance = graph_distance_from_contact(network, direct)
    initial_shell = _radial_order_centered(network, center)
    initial_radial_by_fiber = _radial_by_fiber_centered(network, center)
    stepper = FastStepper(network)
    mapper = ActiveMapper(network, patches)
    nsteps = int(round(run_time / cfg.dt))
    every = max(1, int(round(observe / cfg.dt)))
    frames: list[dict] = []
    vectors = np.zeros((len(patches), 2))

    for step in range(nsteps + 1):
        time = step * cfg.dt
        ramp = min(1.0, time / max(cfg.force_ramp_time, cfg.dt))
        requested = force * ramp
        active, _, vectors = mapper.map(requested, center, weighted=True)
        if step % every == 0 or step == nsteps:
            frames.append(
                _v4_frame(
                    network,
                    center,
                    time,
                    patches,
                    vectors,
                    distance,
                    initial_shell,
                    initial_radial_by_fiber,
                    cell_radius=cfg.cell_radius,
                    requested_force=requested,
                )
            )
        if step == nsteps:
            break
        stepper.step(active, center, cfg.dt)

    return {
        "config": asdict(cfg),
        "spec": spec,
        "network": network,
        "report": report,
        "mode": "fixed-force",
        "geometry": geometry,
        "frames": frames,
        "patches": patches,
        "direct_fibers": direct,
        "graph_distance": distance,
        "cell_radius_constant": bool(
            all(abs(frame["cell_radius"] - cfg.cell_radius) < 1e-12 for frame in frames)
        ),
        "max_displacement": float(np.max(np.linalg.norm(network.r - network.r0, axis=1))),
        "final_delta_radial_order_by_shell": frames[-1]["delta_radial_order_by_shell"].copy(),
        "final_graph_class_metrics": frames[-1]["graph_class_metrics"],
    }


def _clutch_uniforms(cfg: G4V4Config, step: int, channel: int, n_sites: int) -> np.ndarray:
    values = _counter_uniform_vector(
        cfg.counter_seed,
        step,
        channel,
        n_sites * cfg.n_clutches_per_site,
    )
    return values.reshape(n_sites, cfg.n_clutches_per_site)


def _advance_clutches(cfg, state, substrate_speed, step):
    """One load--rupture--rebind update for independent or shared clutches."""

    before_count = state.bound.sum(axis=1)
    if cfg.clutch_mode == "shared":
        site_stiffness = cfg.n_clutches_per_site * cfg.clutch_stiffness
        traction_before = np.where(
            before_count > 0, site_stiffness * state.site_extension, 0.0
        )
    else:
        force_before = cfg.clutch_stiffness * state.extension * state.bound
        traction_before = force_before.sum(axis=1)
    actin_speed = cfg.unloaded_actin_speed * np.maximum(
        0.0, 1.0 - traction_before / cfg.motor_stall_per_site
    )
    relative_speed = np.maximum(0.0, actin_speed - substrate_speed)
    if cfg.clutch_mode == "shared":
        state.site_extension[before_count > 0] += cfg.dt * relative_speed[before_count > 0]
        site_force_before = np.where(
            before_count > 0, site_stiffness * state.site_extension, 0.0
        )
        per_clutch_force = np.divide(
            site_force_before,
            np.maximum(before_count, 1),
            dtype=float,
        )[:, None]
        per_clutch_force = np.repeat(
            per_clutch_force, cfg.n_clutches_per_site, axis=1
        )
    else:
        increment = cfg.dt * np.repeat(
            relative_speed[:, None], cfg.n_clutches_per_site, axis=1
        )
        state.extension[state.bound] += increment[state.bound]
        per_clutch_force = cfg.clutch_stiffness * state.extension
    off_rate = cfg.clutch_off_rate0 * np.exp(
        np.minimum(np.abs(per_clutch_force) / cfg.bell_force, 50.0)
    )
    u_off = _clutch_uniforms(cfg, step, 1, len(state.bound))
    ruptures = state.bound & (u_off < 1.0 - np.exp(-off_rate * cfg.dt))
    state.bound[ruptures] = False
    state.extension[ruptures] = 0.0
    after_break_count = state.bound.sum(axis=1)
    site_failures = (before_count > 0) & (after_break_count == 0)
    state.site_extension[site_failures] = 0.0

    u_on = _clutch_uniforms(cfg, step, 0, len(state.bound))
    on_probability = 1.0 - math.exp(-cfg.clutch_on_rate * cfg.dt)
    binds = (~state.bound) & (u_on < on_probability)
    state.bound[binds] = True
    state.extension[binds] = 0.0

    state.cumulative_ruptures += int(ruptures.sum())
    state.cumulative_site_failures += int(site_failures.sum())
    after_count = state.bound.sum(axis=1)
    state.site_extension[after_count == 0] = 0.0
    if cfg.clutch_mode == "shared":
        total = np.where(after_count > 0, site_stiffness * state.site_extension, 0.0)
        shared = np.divide(total, np.maximum(after_count, 1), dtype=float)
        force = state.bound * shared[:, None]
        state.extension[:] = state.site_extension[:, None] * state.bound
    else:
        force = cfg.clutch_stiffness * state.extension * state.bound
    return (
        force.sum(axis=1),
        actin_speed,
        ruptures,
        binds,
        site_failures,
    )


def _angle_of_patch(network, patch, center) -> float:
    outward = patch_point(network, patch) - center
    return math.atan2(float(outward[1]), float(outward[0]))


def _relocate_failed_sites(network, center, patches, failures, cfg):
    """Relocate a fully detached site using its encountered fibre tangent.

    The outgoing direction is the local collagen tangent oriented away from
    the cell. The next site is the eligible surface material point nearest that
    direction. This is a declared contact-guidance rule: it uses no global
    polarization vector and it acts only after complete site failure.
    """

    if not np.any(failures):
        return patches
    fresh = select_force_geometry(network, center, "normal", cfg)
    if not fresh:
        return patches
    updated = [_copy_patch(patch) for patch in patches]
    used = {patch.fiber for index, patch in enumerate(updated) if not failures[index]}
    for site in np.flatnonzero(failures):
        old = updated[site]
        old_point = patch_point(network, old)
        old_outward = old_point - center
        old_outward /= max(float(np.linalg.norm(old_outward)), 1e-12)
        guidance = _contact_tangent(network, old)
        if float(guidance @ old_outward) < 0.0:
            guidance = -guidance
        available = [patch for patch in fresh if patch.fiber not in used] or fresh
        chosen = min(
            available,
            key=lambda patch: math.acos(
                np.clip(
                    float(
                        guidance
                        @ (
                            (patch_point(network, patch) - center)
                            / max(
                                float(np.linalg.norm(patch_point(network, patch) - center)),
                                1e-12,
                            )
                        )
                    ),
                    -1.0,
                    1.0,
                )
            ),
        )
        updated[site] = _copy_patch(chosen)
        used.add(chosen.fiber)
    return updated


def _event_snapshot(
    network,
    local_beads,
    center,
    time,
    patches,
    state,
    site_force,
    ruptures,
    binds,
    substrate_speed,
):
    return {
        "time": float(time),
        "positions": network.r[local_beads].copy(),
        "center": np.asarray(center).copy(),
        "contact_points": np.asarray([patch_point(network, p) for p in patches]),
        "bound": state.bound.astype(np.uint8).copy(),
        "extension": state.extension.copy(),
        "site_force": np.asarray(site_force).copy(),
        "ruptures": np.asarray(ruptures, dtype=np.uint8).copy(),
        "binds": np.asarray(binds, dtype=np.uint8).copy(),
        "substrate_speed": np.asarray(substrate_speed).copy(),
    }


def run_motor_clutch(
    cfg: G4V4Config = G4V4Config(),
    *,
    moving: bool = False,
    duration: float | None = None,
    sample_interval: float | None = None,
    spec: NetworkSpec | None = None,
    capture_event: bool = True,
) -> dict:
    """G4 v4-C/D: load--slip--recoil cycles with an optional released cell.

    The fixed-cell run uses the two-hour collagen-displacement clock.  The
    moving run uses the six-hour migration clock.  Contact material points are
    changed only after all clutches at a site have detached.
    """

    cfg.validate()
    run_time = (
        cfg.migration_duration if moving else cfg.fixed_duration
    ) if duration is None else float(duration)
    observe = (
        cfg.migration_sample_interval if moving else cfg.fixed_sample_interval
    ) if sample_interval is None else float(sample_interval)
    network, spec, report = build_random_network(cfg, spec=spec)
    center = np.zeros(2)
    patches = select_force_geometry(network, center, "normal", cfg)
    if not patches:
        raise RuntimeError("random network has no eligible clutch sites")
    direct = [int(patch.fiber) for patch in patches]
    distance = graph_distance_from_contact(network, direct)
    initial_shell = _radial_order_centered(network, center)
    initial_radial_by_fiber = _radial_by_fiber_centered(network, center)
    state = V4ClutchState(
        bound=np.zeros((len(patches), cfg.n_clutches_per_site), dtype=bool),
        extension=np.zeros((len(patches), cfg.n_clutches_per_site), dtype=float),
        site_extension=np.zeros(len(patches), dtype=float),
    )
    mapper = ActiveMapper(network, patches)
    stepper = FastStepper(network)
    substrate_speed = np.zeros(len(patches))
    site_force = np.zeros(len(patches))
    actin_speed = np.full(len(patches), cfg.unloaded_actin_speed)
    vectors = np.zeros((len(patches), 2))
    ruptures = np.zeros_like(state.bound)
    binds = np.zeros_like(state.bound)
    nsteps = int(round(run_time / cfg.dt))
    every = max(1, int(round(observe / cfg.dt)))
    event_every = max(1, int(round(cfg.event_sample_interval_v4 / cfg.dt)))
    half_frames = max(1, int(round(cfg.event_half_window_v4 / cfg.event_sample_interval_v4)))
    frames: list[dict] = []
    event_frames: list[dict] = []
    event_log: list[dict] = []
    ring: deque = deque(maxlen=half_frames + 1)
    event_time: float | None = None
    event_end: float | None = None
    # Event microscope: cell + full contact band + 2 um context. Full-field
    # overview frames remain separate, so the high-frequency clip does not
    # duplicate distant, visually static beads 201 times.
    local_mask = np.linalg.norm(network.r0, axis=1) <= cfg.cell_radius + cfg.contact_width + 2.0
    for patch in patches:
        local_mask[network.edges[patch.edge]] = True
    local_beads = np.flatnonzero(local_mask)
    path_length = 0.0

    for step in range(nsteps + 1):
        time = step * cfg.dt
        if step % every == 0 or step == nsteps:
            frames.append(
                _v4_frame(
                    network,
                    center,
                    time,
                    patches,
                    vectors,
                    distance,
                    initial_shell,
                    initial_radial_by_fiber,
                    cell_radius=cfg.cell_radius,
                    requested_force=float(site_force.sum()),
                    bound=state.bound,
                    extension=state.extension,
                    site_force=site_force,
                    actin_speed=actin_speed,
                    substrate_speed=substrate_speed,
                    cumulative_ruptures=state.cumulative_ruptures,
                    cumulative_site_failures=state.cumulative_site_failures,
                )
            )
        if step == nsteps:
            break

        site_force, actin_speed, ruptures, binds, failures = _advance_clutches(
            cfg, state, substrate_speed, step
        )
        event_stamp = (step + 1) * cfg.dt
        for site, clutch in np.argwhere(ruptures):
            event_log.append({"time": event_stamp, "kind": "rupture", "site": int(site), "clutch": int(clutch)})
        for site, clutch in np.argwhere(binds):
            event_log.append({"time": event_stamp, "kind": "bind", "site": int(site), "clutch": int(clutch)})
        for site in np.flatnonzero(failures):
            event_log.append({"time": event_stamp, "kind": "site_failure", "site": int(site)})
            if capture_event and event_time is None and event_stamp >= cfg.minimum_event_time:
                event_time = event_stamp
                event_end = event_stamp + cfg.event_half_window_v4
                event_frames = list(ring)

        active, _, vectors = mapper.map(site_force, center)
        velocity_cell = np.zeros(2, dtype=float)
        if moving:
            # ``vectors`` are cell-on-ECM forces; the cell receives their
            # equal-and-opposite reaction.
            velocity_cell = cell_velocity_from_ecm_forces(vectors, cfg.cell_drag)
            speed = float(np.linalg.norm(velocity_cell))
            if speed > cfg.max_cell_speed:
                velocity_cell *= cfg.max_cell_speed / speed
            delta = cfg.dt * velocity_cell
            center += delta
            path_length += float(np.linalg.norm(delta))

        bead_velocity, _ = stepper.step(active, center, cfg.dt)
        substrate_speed = _relative_substrate_speeds(
            network, bead_velocity, patches, center, velocity_cell
        )

        if np.any(failures):
            patches = _relocate_failed_sites(network, center, patches, failures, cfg)
            mapper.update_patches(patches)
            direct = [int(patch.fiber) for patch in patches]
            distance = graph_distance_from_contact(network, direct)
            for site in np.flatnonzero(failures):
                event_log.append({"time": event_stamp, "kind": "relocate", "site": int(site), "fiber": int(patches[site].fiber)})

        if capture_event and step % event_every == 0:
            detail = _event_snapshot(
                network,
                local_beads,
                center,
                event_stamp,
                patches,
                state,
                site_force,
                ruptures,
                binds,
                substrate_speed,
            )
            if event_time is None:
                ring.append(detail)
            elif event_end is not None and event_stamp <= event_end + 1e-9:
                event_frames.append(detail)

    final_center = np.asarray(center).copy()
    return {
        "config": asdict(cfg),
        "spec": spec,
        "network": network,
        "report": report,
        "mode": "motor-clutch-moving" if moving else "motor-clutch-fixed",
        "moving": bool(moving),
        "frames": frames,
        "event_frames": event_frames,
        "event_time": event_time,
        "event_log": event_log,
        "local_beads": local_beads,
        "patches": patches,
        "graph_distance": distance.copy(),
        "cell_radius_constant": bool(
            all(abs(frame["cell_radius"] - cfg.cell_radius) < 1e-12 for frame in frames)
        ),
        "path_length": float(path_length),
        "net_displacement": float(np.linalg.norm(final_center)),
        "final_center": final_center,
        "max_displacement": float(np.max(np.linalg.norm(network.r - network.r0, axis=1))),
        "site_failures": int(state.cumulative_site_failures),
        "ruptures": int(state.cumulative_ruptures),
    }


