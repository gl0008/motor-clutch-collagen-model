def _small_sample_ci95(values: np.ndarray) -> tuple[float, float]:
    """Two-sided 95% t interval for the predeclared small seed ensemble."""

    values = np.asarray(values, dtype=float)
    if len(values) < 2:
        value = float(values[0]) if len(values) else float("nan")
        return value, value
    critical = {2: 12.706, 3: 4.303, 4: 3.182, 5: 2.776,
                6: 2.571, 7: 2.447, 8: 2.365, 9: 2.306, 10: 2.262}
    t_value = critical.get(len(values), 1.96)
    mean = float(np.mean(values))
    half = float(t_value * np.std(values, ddof=1) / math.sqrt(len(values)))
    return mean - half, mean + half


def run_alignment_ensemble(
    cfg: G4V4Config = G4V4Config(),
    *,
    seeds: tuple[int, ...] = (41, 42, 43, 44, 45),
    duration: float | None = None,
    sample_interval: float | None = None,
) -> dict:
    """Repeat v4-B on independent geometries and test predeclared effects."""

    near_delta: list[float] = []
    one_hop_advantage: list[float] = []
    results: list[dict] = []
    for seed in seeds:
        case_cfg = replace(cfg, seed=int(seed))
        result = run_fixed_force_direction(
            case_cfg,
            geometry="normal",
            duration=duration,
            sample_interval=sample_interval,
        )
        near_delta.append(float(result["final_delta_radial_order_by_shell"][0]))
        graph = result["final_graph_class_metrics"]
        one_hop_advantage.append(
            float(graph["one_hop"]["mean_displacement"] - graph["unconnected"]["mean_displacement"])
        )
        results.append({
            "seed": int(seed),
            "near_delta_radial_order": near_delta[-1],
            "one_hop_minus_unconnected_displacement": one_hop_advantage[-1],
            "contacts": len(result["patches"]),
        })
    near = np.asarray(near_delta)
    hop = np.asarray(one_hop_advantage)
    near_ci = _small_sample_ci95(near)
    hop_ci = _small_sample_ci95(hop)
    return {
        "seeds": [int(seed) for seed in seeds],
        "cases": results,
        "near_delta_mean": float(np.mean(near)),
        "near_delta_ci95": near_ci,
        "near_alignment_excludes_passive_zero": bool(near_ci[0] > 0.0 or near_ci[1] < 0.0),
        "one_hop_advantage_mean": float(np.mean(hop)),
        "one_hop_advantage_ci95": hop_ci,
        "one_hop_exceeds_unconnected": bool(hop_ci[0] > 0.0),
    }


def run_domain_convergence(
    cfg: G4V4Config = G4V4Config(),
    *,
    domain_sizes: tuple[float, ...] = (180.0, 270.0, 360.0),
    duration: float | None = None,
) -> dict:
    """Increase the field while preserving source-fiber areal density."""

    cases = []
    base_density = cfg.n_fibers / cfg.domain_size**2
    for domain in domain_sizes:
        n_fibers = max(20, int(round(base_density * domain**2)))
        case_cfg = replace(cfg, domain_size=float(domain), n_fibers=n_fibers)
        result = run_fixed_force_direction(
            case_cfg,
            duration=duration,
            sample_interval=duration if duration is not None else cfg.fixed_sample_interval,
        )
        cases.append({
            "domain_size": float(domain),
            "n_fibers": int(n_fibers),
            "near_delta_radial_order": float(result["final_delta_radial_order_by_shell"][0]),
            "max_displacement": float(result["max_displacement"]),
        })
    if len(cases) >= 2:
        a = cases[-2]["near_delta_radial_order"]
        b = cases[-1]["near_delta_radial_order"]
        relative = abs(b - a) / max(abs(b), abs(a), 1e-12)
    else:
        relative = float("nan")
    return {
        "cases": cases,
        "last_two_relative_change": float(relative),
        "near_cell_change_below_5_percent": bool(relative < 0.05),
    }


