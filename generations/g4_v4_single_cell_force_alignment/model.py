"""G4 v4: fixed-size single-cell traction on an initially random collagen network.

This generation deliberately imports the validated random geometry and elastic
solver from G4 v3 instead of copying or overwriting them.  It separates two
central objects that looked similar in the old animation but answer different
questions:

* ``run_cavity_benchmark`` is a prescribed contracting *cavity*.  It tests the
  collagen network mechanics and is not a biological model of a shrinking cell.
* every biological-cell run keeps the cell radius fixed.  Continued force is
  generated by actin--clutch loading, not by changing the cell radius.

Units are micrometre (um), nanonewton (nN), and second (s).  Crosslinks are
permanent elastic material-point links.  There is no SLS, Brownian force,
plasticity, crosslink rupture, cell growth, or spheroid biology in this module.
"""

